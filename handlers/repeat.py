"""Реакция на повторяющийся вопрос: «я же только что ответила»."""
import random

import config

# Собеседник повторил то, на что Юля уже ответила (1-й повтор)
FIRST = [
    "Я же только что ответила)",
    "Эй, я же только что написала",
    "Так я же уже ответила, глянь выше",
    "Ты читаешь вообще? Я только что ответила",
    "Я ж только что ответила)",
]
# 2-й и 3-й повтор — уже раздражается
IRRITATED = [
    "Ты издеваешься? Я же ответила",
    "Ну я же сказала уже, ты не видишь?",
    "Это уже третий раз, прочитай выше",
    "Слушай, ну хватит, я уже ответила",
]
# то же, но с матом (используется с вероятностью SWEAR_CHANCE)
IRRITATED_MAT = [
    "Ты че, бля, издеваешься? Я же ответила",
    "Блин, ну я уже сказала, читай выше",
    "Да я тебе уже ответила, ну пиздец",
    "Ты прикалываешься? Я ж уже сказала, бля",
]
MAX_REPEATS = 4   # после стольких повторов Юля просто игнорирует


def pick(times_answered: int) -> str:
    """times_answered — сколько раз этот вопрос уже был отвечен."""
    if times_answered <= 1:
        return random.choice(FIRST)
    if config.SWEAR_CHANCE > 0 and random.random() * 100 < config.SWEAR_CHANCE * 2:
        return random.choice(IRRITATED_MAT)
    return random.choice(IRRITATED)
